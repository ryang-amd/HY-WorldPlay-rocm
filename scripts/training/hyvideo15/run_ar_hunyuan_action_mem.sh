# Rewrite paths in train.json to use DATA_PATH (handles data copied/moved to new location)
python3 -c "
import json
import os
data_path = os.path.abspath('${DATA_PATH}')
train_json = os.path.join(data_path, 'train.json')
if os.path.exists(train_json):
    with open(train_json) as f:
        data = json.load(f)
    if data:
        old_base = data[0]['latent_path'].rsplit('/latents/', 1)[0]
        if old_base != data_path:
            for item in data:
                for key in ('latent_path', 'pose_path', 'action_path'):
                    if key in item and item[key]:
                        item[key] = item[key].replace(old_base, data_path)
            with open(train_json, 'w') as f:
                json.dump(data, f, indent=2)
            print(f'Updated train.json paths: {old_base} -> {data_path}')
"

