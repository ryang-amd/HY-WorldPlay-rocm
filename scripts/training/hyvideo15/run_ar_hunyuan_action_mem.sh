# Training arguments
training_args=(
  --mode finetuning
  --json_path ${DATA_PATH}/train.json
  --causal
  --action
  --i2v_rate 0.2
  --train_time_shift 3.0
  --window_frames 32
  --wandb_key "${WANDB_API_KEY}"
  --wandb_entity "${WANDB_ENTITY}"
  --tracker_project_name "hy-worldplay-vkitti"
  --output_dir /data/ruijyang/training_output/run4_full_run
