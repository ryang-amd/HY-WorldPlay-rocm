import json, os
from pathlib import Path
cfg_path = Path(os.path.expandvars("${DC_MODEL_DIR}/config.json"))
cfg = json.loads(cfg_path.read_text())
dc_enabled = bool(cfg.get("dc_enabled", False))
double_depth = int(cfg.get("mm_double_blocks_depth", 0))
start = int(cfg.get("dc_chunk_start_block", 0))
end = int(cfg.get("dc_chunk_end_block", -1))
if end < 0:
    end = double_depth
if dc_enabled:
    dc_blocks = max(0, min(end, double_depth) - start)
    print(f"[DC] Double-stream blocks: {double_depth}, DC active on [{start}, {end}): {dc_blocks} blocks chunked")
    if dc_blocks == 0:
        print("[WARN] dc_chunk_start_block >= dc_chunk_end_block; DC path will not be exercised.")
PY

