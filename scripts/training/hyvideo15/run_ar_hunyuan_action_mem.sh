  --validation_sampling_steps "50"s
  --validation_guidance_scale "6.0"
)

# Optimizer arguments
# Higher LR (5e-5) for faster learning on small dataset (100 samples).
# Cosine schedule with min_lr_ratio=0.1 decays to 5e-6 over 500 steps.
optimizer_args=(
  --learning_rate 5e-5
  --lr_scheduler "cosine_with_min_lr"
  --lr_warmup_steps 20
